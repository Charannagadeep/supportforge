#!/usr/bin/env python3
"""Deterministic evidence auditor for SupportForge demos (no cloud LLM)."""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

REQUIRED = [
    ("problem_statement", ["customer/description.md"]),
    ("environment_manifest", ["incoming/environment.json", "incoming/env.txt"]),
    ("gpu_snapshot", ["incoming/nvidia-smi.txt", "incoming/nvidia_smi.txt"]),
    ("primary_logs", ["incoming/*.log"]),
    ("steps_tried", ["customer/steps-tried.md"]),
]


def resolve(case: Path, patterns: list[str]) -> list[Path]:
    found: list[Path] = []
    for pat in patterns:
        if "*" in pat:
            found.extend(sorted(case.glob(pat)))
        else:
            p = case / pat
            if p.exists() and p.stat().st_size > 0:
                found.append(p)
    return [p for p in found if p.exists() and p.stat().st_size > 0]


def status_for(paths: list[Path]) -> str:
    if not paths:
        return "missing"
    # weak if all tiny
    if all(p.stat().st_size < 40 for p in paths):
        return "weak"
    return "present"


def extract_timeline(case: Path) -> list[dict]:
    events = []
    for log in sorted((case / "incoming").glob("*.log")) if (case / "incoming").exists() else []:
        for i, line in enumerate(log.read_text(errors="replace").splitlines(), 1):
            if re.search(r"ERROR|OutOfMemory|CUDA out of memory|Xid|segfault|FATAL", line, re.I):
                ts = line.split(" ", 1)[0] if line[:1].isdigit() or line[:1] == "2" else "unknown"
                events.append(
                    {
                        "time": ts,
                        "summary": line.strip()[:160],
                        "citation": f"{log.relative_to(case)}:{i}",
                    }
                )
    return events


def main() -> int:
    if len(sys.argv) < 2:
        print("Usage: audit_case.py <case-dir>", file=sys.stderr)
        return 2
    case = Path(sys.argv[1]).resolve()
    if not case.is_dir():
        print(f"Not a directory: {case}", file=sys.stderr)
        return 2

    rows = []
    present = 0
    for key, pats in REQUIRED:
        paths = resolve(case, pats)
        st = status_for(paths)
        if st == "present":
            present += 1
        rows.append(
            {
                "item": key,
                "status": st,
                "paths": [str(p.relative_to(case)) for p in paths],
            }
        )
    pct = round(100 * present / len(REQUIRED))
    audit = {
        "case_id": case.name,
        "completeness_percent": pct,
        "evidence": rows,
        "updated": datetime.now(timezone.utc).isoformat(),
    }
    (case / "audit.json").write_text(json.dumps(audit, indent=2) + "\n")

    missing = [r for r in rows if r["status"] != "present"]
    req_lines = [f"# Requests — {case.name}", "", f"Completeness: **{pct}%**", ""]
    if missing:
        req_lines.append("Please provide:")
        for r in missing:
            req_lines.append(f"- **{r['item']}** (status: {r['status']})")
    else:
        req_lines.append("All required evidence present.")
    outbox = case.parents[1] / "outbox" if (case.parents[1] / "outbox").exists() else case / ".."
    # Prefer project workspace outbox when case lives under workspace/cases
    candidates = [
        case.parent.parent / "outbox",
        case.parents[2] / "workspace" / "outbox" if len(case.parents) > 2 else None,
        Path(__file__).resolve().parents[1] / "workspace" / "outbox",
    ]
    out_dir = next((p for p in candidates if p and p.exists()), case)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{case.name}-requests.md").write_text("\n".join(req_lines) + "\n")

    events = extract_timeline(case)
    if events:
        tl = [f"# Timeline — {case.name}", ""]
        for e in events:
            tl.append(f"- **{e['time']}** — {e['summary']}")
            tl.append(f"  - cite: `{e['citation']}`")
        (case / "timeline.md").write_text("\n".join(tl) + "\n")

    # Minimal handoff skeleton
    hyp = []
    smi = resolve(case, ["incoming/nvidia-smi.txt", "incoming/nvidia_smi.txt"])
    if any("CUDA out of memory" in (p.read_text(errors="replace")) for p in resolve(case, ["incoming/*.log"])):
        hyp.append("1. GPU memory exhaustion during serving init (supported by serving.log ERROR lines).")
    if smi and "train_scratch" in smi[0].read_text(errors="replace"):
        hyp.append("2. Competing abandoned GPU process `train_scratch.py` holding majority of memory (supported by nvidia-smi.txt).")

    handoff = f"""# Engineering handoff — {case.name}

**Generated by:** SupportForge audit_case.py (local deterministic assist)
**Updated:** {audit['updated']}
**Completeness:** {pct}%

## Summary

Case {case.name} reviewed locally. Completeness {pct}%. See evidence table and requests.

## Completeness

| Item | Status | Path |
|------|--------|------|
""" + "\n".join(
        f"| {r['item']} | {r['status']} | {', '.join(r['paths']) or '—'} |" for r in rows
    ) + f"""

## Timeline

{(case / 'timeline.md').read_text() if (case / 'timeline.md').exists() else '_No ERROR/OOM lines extracted yet._'}

## Hypotheses (ranked)

{chr(10).join(hyp) if hyp else '_Insufficient evidence for ranked hypotheses._'}

## Unknowns

{chr(10).join(f"- Missing/weak: {r['item']}" for r in missing) or '- None for required set'}

## Next checks

1. If competing processes appear in nvidia-smi, confirm owner and stop abandoned jobs before resizing the model.
2. Re-run serving with recorded gpu_memory_utilization / max_model_len after memory is free.
3. Attach driver/CUDA confirmation if crash persists without OOM.

## Customer requests (blocking)

See `{case.name}-requests.md`.

---
*Private case data — local processing only.*
"""
    (out_dir / f"{case.name}-handoff.md").write_text(handoff)
    print(json.dumps({"completeness_percent": pct, "outbox": str(out_dir), "missing": [r["item"] for r in missing]}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
